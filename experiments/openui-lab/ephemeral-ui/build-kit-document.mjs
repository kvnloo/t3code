#!/usr/bin/env node
// Regenerates packages/client-runtime/src/ephemeralUiKitDocument.generated.ts from a
// kvnloo/ephemeral-ui checkout: the kit's own card code, CSS and public fixtures in one offline
// HTML document. Hosts insert the card list between HEAD and TAIL and show it in a sandbox.
//
//   node experiments/openui-lab/ephemeral-ui/build-kit-document.mjs <ephemeral-ui checkout>
//
// Needs esbuild on PATH (or ESBUILD=/path/to/esbuild). Output is deterministic for a revision.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const kit = resolve(process.argv[2] ?? "");
const esbuild = process.env.ESBUILD ?? "esbuild";
const out = resolve(here, "../../../packages/client-runtime/src/ephemeralUiKitDocument.generated.ts");

const revision = execFileSync("git", ["-C", kit, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const dirty = execFileSync("git", ["-C", kit, "status", "--porcelain", "--untracked-files=no"], { encoding: "utf8" }).trim();
if (dirty) throw new Error(`ephemeral-ui checkout has local changes:\n${dirty}`);

const read = (path) => readFileSync(join(kit, path), "utf8");
const json = (path) => JSON.parse(read(path));
const run = (args, input) => execFileSync(esbuild, args, { cwd: kit, input, encoding: "utf8", maxBuffer: 1 << 28 });

const script = run(["--bundle", "--format=iife", "--minify", "--target=es2020", "--log-level=warning"], readFileSync(join(here, "card-entry.js"), "utf8"));
const css = run(["--loader=css", "--minify", "--log-level=warning"], ["styles.css", "trace.css", "intent.css", "infra.css"].map(read).join("\n"));

// App icons stay monograms (the kit's default in T3 Code), so the SVG paths are not shipped.
const apps = json("data/apps.json");
const data = {
  "data/apps.json": { ...apps, apps: apps.apps.map(({ path: _path, ...app }) => app) },
  "data/themes.json": json("data/themes.json"),
  "data/trace-fixture.json": json("data/trace-fixture.json"),
  "data/intent-snapshot.json": json("data/intent-snapshot.json"),
};
const kinds = json("schema/card.v0.json").properties.kind.enum;

// JSON and code inside <script> must never close the element early.
const safe = (text) => text.replaceAll("</", "<\\/").replaceAll("<!--", "<\\!--");
const hostCss =
  "html,body{margin:0;background:transparent}#t3-kit-root{display:grid;grid-template-columns:minmax(0,1fr);gap:12px;padding:2px}" +
  ".t3-kit-cell{min-width:0}.t3-kit-cell>.eu-card{max-width:none;width:auto;margin:0}" +
  ".t3-kit-fail{padding:10px 12px;border:1px solid var(--h-danger,#e5484d);border-radius:10px;color:var(--h-fg,#ddd);font:13px system-ui}";
const head =
  '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' +
  `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:; font-src data:">` +
  `<style>${css}${hostCss}</style>` +
  `<script type="application/json" id="t3-kit-data">${safe(JSON.stringify(data))}</script><script>window.__T3_KIT_CARDS=`;
const tail = `</script></head><body><div id="t3-kit-root"></div><script>${safe(script)}</script></body></html>`;

writeFileSync(
  out,
  `// Generated by experiments/openui-lab/ephemeral-ui/build-kit-document.mjs. Do not edit.\n` +
    `// Source: https://github.com/kvnloo/ephemeral-ui/tree/${revision} (card code, CSS and public fixtures).\n` +
    `/* eslint-disable */\n` +
    `export const EPHEMERAL_UI_KIT_REVISION = ${JSON.stringify(revision)};\n` +
    `export const EPHEMERAL_UI_KIT_KINDS = ${JSON.stringify(kinds)} as const;\n` +
    `export const EPHEMERAL_UI_KIT_HEAD = ${JSON.stringify(head)};\n` +
    `export const EPHEMERAL_UI_KIT_TAIL = ${JSON.stringify(tail)};\n`,
);
console.log(`wrote ${out} from ${revision}: ${kinds.length} kinds, ${(head.length + tail.length) >> 10} KiB`);
